"""Validates docs/traceability.yaml and renders docs/BLUEPRINT_TRACEABILITY.md.

Fails if a row claims 'done' without an existing test, cites a file that does not exist,
or marks 'blocked' without naming the blocker. The report cannot claim more than the repo
contains.
"""
from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs" / "traceability.yaml"
TARGET = ROOT / "docs" / "BLUEPRINT_TRACEABILITY.md"
STATUSES = ("done", "partial", "blocked", "not_started")


def test_exists(reference: str) -> bool:
    path_text, _, name = reference.partition("::")
    path = ROOT / path_text
    if not path.exists():
        return False
    if not name:
        return True
    name = name.split("[")[0].split("::")[-1]
    return re.search(rf"\b{re.escape(name)}\b", path.read_text(encoding="utf-8")) is not None


def check(rows: list[dict]) -> list[str]:
    problems: list[str] = []
    seen: set[str] = set()
    for row in rows:
        rid = row["id"]
        if rid in seen:
            problems.append(f"{rid}: duplicate id")
        seen.add(rid)
        if row["status"] not in STATUSES:
            problems.append(f"{rid}: unknown status {row['status']}")
        for path in row.get("code", []):
            if not (ROOT / path).exists():
                problems.append(f"{rid}: missing file {path}")
        for reference in row.get("tests", []):
            if not test_exists(reference):
                problems.append(f"{rid}: missing test {reference}")
        if row["status"] == "done" and not row.get("tests"):
            problems.append(f"{rid}: done with no test")
        if row["status"] == "blocked" and not row.get("blocker"):
            problems.append(f"{rid}: blocked with no blocker named")
    return problems


def render(rows: list[dict]) -> str:
    counts = Counter(r["status"] for r in rows)
    lines = [
        "# Blueprint traceability",
        "",
        "Generated by `scripts/check_traceability.py` from `docs/traceability.yaml`. Do not edit by hand.",
        "",
        f"**{len(rows)} requirements:** " + ", ".join(f"{counts.get(s, 0)} {s.replace('_', ' ')}" for s in STATUSES),
        "",
        "`done` means implemented and tested in this repository. Proof against a live provider is a separate blocked row.",
        "",
        "| ID | Source | Requirement | Status | Code | Tests | Blocker |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        code = "<br>".join(f"`{Path(c).name}`" for c in row.get("code", []))
        tests = "<br>".join(f"`{t.split('::')[-1]}`" for t in row.get("tests", []))
        lines.append(
            f"| {row['id']} | {row['source']} | {row['requirement']} | {row['status']} | {code} | {tests} | {row.get('blocker', '')} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    rows = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    problems = check(rows)
    TARGET.write_text(render(rows), encoding="utf-8", newline="\n")
    for problem in problems:
        print(problem)  # noqa: T201 - command-line tool output
    print(f"{len(rows)} requirements, {len(problems)} problems")  # noqa: T201
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
